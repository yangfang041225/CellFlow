def card(key):
    """取一张卡片；缺失时返回 None，让界面自己降级显示。"""
    entry = METHOD_CONTENT.get(key) or {}
    if not entry:
        return None
    return entry


def completeness():
    """给测试用：返回 {key: 缺失字段列表}。

    例外：尚未接入的方法本来就不产出结果，`we_output` 允许是空列表；
    但键本身仍必须存在，漏写整段仍会被检出。
    """
    out = {}
    for key, entry in METHOD_CONTENT.items():
        if not entry:
            out[key] = ['<整张卡片为空>'] + list(REQUIRED_CARD_KEYS)
            continue
        missing = [f for f in REQUIRED_CARD_KEYS
                   if f not in entry or (not entry[f] and f != 'we_output')]
        tech = entry.get('tech') or {}
        missing += ['tech.' + f for f in REQUIRED_TECH_KEYS if not tech.get(f)]
        out[key] = missing
    return out
